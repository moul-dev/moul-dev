// Package filegate decides who may read a stored upload. It records who uploaded each file
// (_files) and which record fields reference it (_file_refs), validates file field values, and
// signs the short-lived URLs that let browsers load files of records that are not public.
package filegate

import (
	"crypto/hmac"
	"crypto/sha256"
	"database/sql"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"net/url"
	"regexp"
	"strconv"
	"strings"
	"sync"
	"time"

	"github.com/moul-dev/moul-dev/internal/schema"
	"github.com/pocketbase/dbx"
)

const (
	filesTable = "_files"
	refsTable  = "_file_refs"

	// SigParam is the query parameter carrying a file URL signature.
	SigParam = "sig"

	// DefaultURLTTL is how long a signed file URL stays valid at least.
	DefaultURLTTL = time.Hour

	// maxFilesPerField bounds a file list when the field sets no Max.
	maxFilesPerField = 100
	// maxFileString bounds every string inside a file object.
	maxFileString = 512
)

// idPattern matches an upload id as generated by util.RandomID.
var idPattern = regexp.MustCompile(`^[A-Za-z0-9]{15}$`)

// ValidID reports whether id has the shape of an upload id.
func ValidID(id string) bool {
	return idPattern.MatchString(id)
}

// Ref is one record field that references an upload.
type Ref struct {
	FileID   string `db:"fileId"`
	Moul     string `db:"moul"`
	RecordID string `db:"recordId"`
	Field    string `db:"field"`
}

// Gate tracks uploads and their references in db and signs file URLs with secret.
type Gate struct {
	db     *dbx.DB
	secret []byte
	ttl    time.Duration
	now    func() time.Time

	publicMu    sync.Mutex
	publicCache map[string]time.Time
}

// New returns a Gate. A zero ttl uses DefaultURLTTL.
func New(db *dbx.DB, secret []byte, ttl time.Duration) *Gate {
	if ttl <= 0 {
		ttl = DefaultURLTTL
	}
	return &Gate{db: db, secret: secret, ttl: ttl, now: time.Now, publicCache: map[string]time.Time{}}
}

// RecordUpload stores who uploaded file id (ownerMoul/ownerID are empty for the admin key).
func (g *Gate) RecordUpload(id, ownerMoul, ownerID string) error {
	_, err := g.db.Insert(filesTable, dbx.Params{
		"id":        id,
		"ownerMoul": ownerMoul,
		"ownerId":   ownerID,
		"createdAt": g.now().UTC().Format(time.RFC3339),
	}).Execute()
	if err != nil {
		return fmt.Errorf("failed to record upload %s: %w", id, err)
	}
	return nil
}

// Uploader returns who uploaded file id; found is false for an unknown file.
func (g *Gate) Uploader(id string) (ownerMoul, ownerID string, found bool, err error) {
	var row struct {
		OwnerMoul string `db:"ownerMoul"`
		OwnerID   string `db:"ownerId"`
	}
	err = g.db.Select("ownerMoul", "ownerId").From(filesTable).Where(dbx.HashExp{"id": id}).One(&row)
	if errors.Is(err, sql.ErrNoRows) {
		return "", "", false, nil
	}
	if err != nil {
		return "", "", false, fmt.Errorf("failed to look up upload %s: %w", id, err)
	}
	return row.OwnerMoul, row.OwnerID, true, nil
}

// ForgetUpload removes file id and its references (after the stored file is deleted).
func (g *Gate) ForgetUpload(id string) error {
	if _, err := g.db.Delete(refsTable, dbx.HashExp{"fileId": id}).Execute(); err != nil {
		return fmt.Errorf("failed to delete references of %s: %w", id, err)
	}
	if _, err := g.db.Delete(filesTable, dbx.HashExp{"id": id}).Execute(); err != nil {
		return fmt.Errorf("failed to delete upload %s: %w", id, err)
	}
	g.forgetPublic(id)
	return nil
}

// Refs returns every record field that references file id.
func (g *Gate) Refs(id string) ([]Ref, error) {
	var refs []Ref
	err := g.db.Select("fileId", "moul", "recordId", "field").From(refsTable).Where(dbx.HashExp{"fileId": id}).All(&refs)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return nil, fmt.Errorf("failed to read references of %s: %w", id, err)
	}
	return refs, nil
}

// RecordRefs returns the file ids each field of record (moul, recordID) references.
func (g *Gate) RecordRefs(moul, recordID string) (map[string][]string, error) {
	var refs []Ref
	err := g.db.Select("fileId", "moul", "recordId", "field").From(refsTable).
		Where(dbx.HashExp{"moul": moul, "recordId": recordID}).All(&refs)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return nil, fmt.Errorf("failed to read references of %s/%s: %w", moul, recordID, err)
	}
	out := map[string][]string{}
	for _, r := range refs {
		out[r.Field] = append(out[r.Field], r.FileID)
	}
	return out, nil
}

// SetRecordRefs replaces the references of record (moul, recordID) with fieldFiles.
func (g *Gate) SetRecordRefs(moul, recordID string, fieldFiles map[string][]string) error {
	err := g.db.Transactional(func(tx *dbx.Tx) error {
		if _, err := tx.Delete(refsTable, dbx.HashExp{"moul": moul, "recordId": recordID}).Execute(); err != nil {
			return err
		}
		for field, ids := range fieldFiles {
			for _, id := range ids {
				_, err := tx.NewQuery("INSERT OR IGNORE INTO " + refsTable + " (fileId, moul, recordId, field) VALUES ({:f}, {:m}, {:r}, {:field})").
					Bind(dbx.Params{"f": id, "m": moul, "r": recordID, "field": field}).Execute()
				if err != nil {
					return err
				}
				g.forgetPublic(id)
			}
		}
		return nil
	})
	if err != nil {
		return fmt.Errorf("failed to store file references of %s/%s: %w", moul, recordID, err)
	}
	return nil
}

// DeleteRecordRefs drops the references of a deleted record.
func (g *Gate) DeleteRecordRefs(moul, recordID string) error {
	return g.SetRecordRefs(moul, recordID, nil)
}

// DeleteMoulRefs drops every reference held by collection moul (the collection was deleted).
func (g *Gate) DeleteMoulRefs(moul string) error {
	if _, err := g.db.Delete(refsTable, dbx.HashExp{"moul": moul}).Execute(); err != nil {
		return fmt.Errorf("failed to delete file references of %s: %w", moul, err)
	}
	g.publicMu.Lock()
	g.publicCache = map[string]time.Time{}
	g.publicMu.Unlock()
	return nil
}

// RebuildMoulRefs recomputes the references of every record of m from its stored file fields
// (after a bulk import that bypassed the record handlers).
func (g *Gate) RebuildMoulRefs(m *schema.Moul) error {
	var cols []string
	for _, f := range m.Fields {
		if f.Type == "file" {
			cols = append(cols, f.Name)
		}
	}
	if len(cols) == 0 {
		return nil
	}
	var rows []dbx.NullStringMap
	if err := g.db.Select(append([]string{"id"}, cols...)...).From(m.Name).All(&rows); err != nil && !errors.Is(err, sql.ErrNoRows) {
		return fmt.Errorf("failed to read %s for file references: %w", m.Name, err)
	}
	for _, row := range rows {
		fieldFiles := map[string][]string{}
		for _, col := range cols {
			if v, ok := row[col]; ok && v.Valid && v.String != "" {
				var decoded interface{}
				if err := json.Unmarshal([]byte(v.String), &decoded); err != nil {
					continue
				}
				fieldFiles[col] = FileIDs(decoded)
			}
		}
		if err := g.SetRecordRefs(m.Name, row["id"].String, fieldFiles); err != nil {
			return err
		}
	}
	return nil
}

// --- public decision cache -------------------------------------------------------------

const publicCacheTTL = 30 * time.Second

// CachedPublic reports whether file id was recently found to be public.
func (g *Gate) CachedPublic(id string) bool {
	g.publicMu.Lock()
	defer g.publicMu.Unlock()
	until, ok := g.publicCache[id]
	return ok && g.now().Before(until)
}

// RememberPublic caches that file id is referenced by a publicly viewable record.
func (g *Gate) RememberPublic(id string) {
	g.publicMu.Lock()
	defer g.publicMu.Unlock()
	if len(g.publicCache) > 10000 {
		g.publicCache = map[string]time.Time{}
	}
	g.publicCache[id] = g.now().Add(publicCacheTTL)
}

func (g *Gate) forgetPublic(id string) {
	g.publicMu.Lock()
	defer g.publicMu.Unlock()
	delete(g.publicCache, id)
}

// --- signed URLs ------------------------------------------------------------------------

// Sign returns the signature query value for file id. Expiries are aligned to ttl windows so the
// same URL is handed out for a while (browsers can cache it), and every URL stays valid for at
// least ttl.
func (g *Gate) Sign(id string) string {
	window := int64(g.ttl / time.Second)
	exp := (g.now().Unix()/window + 2) * window
	return strconv.FormatInt(exp, 10) + "." + g.mac(id, exp)
}

// Verify reports whether sig is an unexpired signature for file id.
func (g *Gate) Verify(id, sig string) bool {
	expStr, mac, ok := strings.Cut(sig, ".")
	if !ok {
		return false
	}
	exp, err := strconv.ParseInt(expStr, 10, 64)
	if err != nil || g.now().Unix() > exp {
		return false
	}
	return hmac.Equal([]byte(mac), []byte(g.mac(id, exp)))
}

func (g *Gate) mac(id string, exp int64) string {
	h := hmac.New(sha256.New, g.secret)
	h.Write([]byte(id + "|" + strconv.FormatInt(exp, 10)))
	return base64.RawURLEncoding.EncodeToString(h.Sum(nil))
}

// SignValue returns a copy of a file field value (one file object or a list) whose url and
// thumbnail urls carry a signature.
func (g *Gate) SignValue(value interface{}) interface{} {
	switch v := value.(type) {
	case map[string]interface{}:
		return g.signObject(v)
	case []interface{}:
		out := make([]interface{}, len(v))
		for i, item := range v {
			out[i] = g.SignValue(item)
		}
		return out
	}
	return value
}

func (g *Gate) signObject(obj map[string]interface{}) map[string]interface{} {
	out := make(map[string]interface{}, len(obj))
	for k, v := range obj {
		out[k] = v
	}
	id, _ := obj["id"].(string)
	if !ValidID(id) {
		return out
	}
	sig := g.Sign(id)
	withSig := func(u string) string {
		if !strings.HasPrefix(u, "/storage/") {
			return u
		}
		return u + "?" + SigParam + "=" + url.QueryEscape(sig)
	}
	if u, ok := obj["url"].(string); ok {
		out["url"] = withSig(u)
	}
	if thumbs, ok := obj["thumbs"].(map[string]interface{}); ok {
		signed := make(map[string]interface{}, len(thumbs))
		for k, v := range thumbs {
			if u, ok := v.(string); ok {
				signed[k] = withSig(u)
			} else {
				signed[k] = v
			}
		}
		out["thumbs"] = signed
	}
	return out
}

// --- file field values ------------------------------------------------------------------

// fileKeys are the keys a stored file object may carry.
var fileKeys = map[string]bool{
	"id": true, "filename": true, "url": true, "thumbhash": true, "thumbs": true,
	"size": true, "createdAt": true, "width": true, "height": true,
}

// thumbKeys are the semantic sizes of an image upload.
var thumbKeys = map[string]bool{"sm": true, "md": true, "lg": true}

// NormalizeValue validates a file field value and returns it in stored form with the ids it
// references. A value is one file object, a list of them, or nil. Every url must point to own
// storage under the object's upload id; signatures and the S3 URL prefix (s3Prefix, "" when S3 is
// off) are stripped, so the stored url is always /storage/<id>/<name>. maxItems bounds a list (0
// uses the default).
func NormalizeValue(value interface{}, s3Prefix string, maxItems int) (interface{}, []string, error) {
	if maxItems <= 0 {
		maxItems = maxFilesPerField
	}
	switch v := value.(type) {
	case nil:
		return nil, nil, nil
	case map[string]interface{}:
		obj, id, err := normalizeObject(v, s3Prefix)
		if err != nil {
			return nil, nil, err
		}
		return obj, []string{id}, nil
	case []interface{}:
		if len(v) > maxItems {
			return nil, nil, fmt.Errorf("holds at most %d files", maxItems)
		}
		out := make([]interface{}, 0, len(v))
		ids := make([]string, 0, len(v))
		for _, item := range v {
			m, ok := item.(map[string]interface{})
			if !ok {
				return nil, nil, fmt.Errorf("must contain file objects")
			}
			obj, id, err := normalizeObject(m, s3Prefix)
			if err != nil {
				return nil, nil, err
			}
			out = append(out, obj)
			ids = append(ids, id)
		}
		return out, ids, nil
	}
	return nil, nil, fmt.Errorf("must be a file object or a list of file objects")
}

func normalizeObject(obj map[string]interface{}, s3Prefix string) (map[string]interface{}, string, error) {
	out := make(map[string]interface{}, len(obj))
	rawURL, _ := obj["url"].(string)
	urlID, path, err := storagePath(rawURL, s3Prefix)
	if err != nil {
		return nil, "", err
	}
	id, _ := obj["id"].(string)
	if id == "" {
		id = urlID
	}
	if id != urlID {
		return nil, "", fmt.Errorf("file url does not belong to file %q", id)
	}
	for k, v := range obj {
		if !fileKeys[k] {
			return nil, "", fmt.Errorf("unknown file attribute %q", k)
		}
		switch k {
		case "url", "id":
			continue
		case "thumbs":
			thumbs, ok := v.(map[string]interface{})
			if !ok {
				return nil, "", fmt.Errorf("thumbs must be an object")
			}
			clean := make(map[string]interface{}, len(thumbs))
			for size, tv := range thumbs {
				tu, ok := tv.(string)
				if !thumbKeys[size] || !ok {
					return nil, "", fmt.Errorf("invalid thumbnail %q", size)
				}
				thumbID, thumbPath, err := storagePath(tu, s3Prefix)
				if err != nil {
					return nil, "", err
				}
				if thumbID != id {
					return nil, "", fmt.Errorf("thumbnail %q does not belong to file %q", size, id)
				}
				clean[size] = thumbPath
			}
			out[k] = clean
		case "size", "width", "height":
			n, ok := v.(float64)
			if !ok || n < 0 || n > 1<<40 {
				return nil, "", fmt.Errorf("%s must be a non-negative number", k)
			}
			out[k] = n
		default:
			s, ok := v.(string)
			if !ok || len(s) > maxFileString {
				return nil, "", fmt.Errorf("%s must be a string of at most %d bytes", k, maxFileString)
			}
			out[k] = s
		}
	}
	out["id"] = id
	out["url"] = path
	return out, id, nil
}

// storagePath validates a file url and returns its upload id and canonical /storage path.
func storagePath(raw, s3Prefix string) (string, string, error) {
	if raw == "" {
		return "", "", fmt.Errorf("file url is required")
	}
	if len(raw) > maxFileString*2 {
		return "", "", fmt.Errorf("file url is too long")
	}
	u := raw
	if i := strings.IndexByte(u, '?'); i >= 0 {
		u = u[:i]
	}
	var rest string
	switch {
	case strings.HasPrefix(u, "/storage/"):
		rest = strings.TrimPrefix(u, "/storage/")
	case s3Prefix != "" && strings.HasPrefix(u, s3Prefix):
		rest = strings.TrimPrefix(u, s3Prefix)
	default:
		return "", "", fmt.Errorf("file url must point to uploaded storage")
	}
	id, name, ok := strings.Cut(rest, "/")
	if !ok || !ValidID(id) || name == "" || strings.Contains(name, "/") || strings.Contains(name, "..") ||
		strings.Contains(name, "%") || strings.Contains(name, "\\") {
		return "", "", fmt.Errorf("file url must point to uploaded storage")
	}
	return id, "/storage/" + id + "/" + name, nil
}

// FileIDs returns the upload ids a stored file field value references.
func FileIDs(value interface{}) []string {
	var ids []string
	collect := func(obj map[string]interface{}) {
		if id, ok := obj["id"].(string); ok && ValidID(id) {
			ids = append(ids, id)
			return
		}
		if u, ok := obj["url"].(string); ok {
			if id, _, err := storagePath(u, ""); err == nil {
				ids = append(ids, id)
			}
		}
	}
	switch v := value.(type) {
	case map[string]interface{}:
		collect(v)
	case []interface{}:
		for _, item := range v {
			if m, ok := item.(map[string]interface{}); ok {
				collect(m)
			}
		}
	}
	return ids
}
